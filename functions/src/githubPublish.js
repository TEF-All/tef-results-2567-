/**
 * Publishes a confirmed draft to the public GitHub Pages repo.
 *
 * Uses the GitHub REST "Contents" API directly over `fetch` (Node 20 has a
 * built-in global fetch — no @octokit/rest dependency needed for the ~4
 * file writes this does per publish). The token is read from a Cloud
 * Functions *secret* (see index.js `defineSecret('GITHUB_TOKEN')`) and is
 * never exposed to the admin frontend.
 *
 * This file intentionally only ever touches:
 *   - tef_master_data_<year>.json / .js   (new per-year data, created/updated)
 *   - index.html / tef_results_webapp.html (one status-flip line each, plus
 *     adding the <script> tag for that year's data file the first time)
 * It never writes to tef_master_data.json/.js (year 2567) at all.
 */

const { GITHUB_OWNER, GITHUB_REPO, GITHUB_BRANCH } = require('./schema');

const API_BASE = `https://api.github.com/repos/${GITHUB_OWNER}/${GITHUB_REPO}/contents`;

function authHeaders(token) {
  return {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'tef-admin-import-system',
  };
}

// Wraps a raw GitHub REST error into a message that's actually useful to an
// admin looking at the "เผยแพร่ไม่สำเร็จ" alert in the browser — Cloud
// Functions callable errors hide the real Error.message from the client for
// any error that isn't an HttpsError, so without this wrapping every GitHub
// API failure (bad/expired token, no repo access, rate limit, etc.) shows up
// as a useless generic "INTERNAL" with no indication of what actually broke.
function githubErrorMessage(status, path, bodyText) {
  let parsed = null;
  try {
    parsed = JSON.parse(bodyText);
  } catch (_) {
    // body wasn't JSON — fall through, use bodyText raw below
  }
  const ghMessage = parsed?.message || bodyText || '';

  if (status === 401) {
    return (
      `GITHUB_TOKEN ไม่ถูกต้องหรือหมดอายุ (GitHub ตอบ 401 Bad credentials ตอนเข้าถึง ${path}) — ` +
      `ต้องสร้าง Personal Access Token ใหม่แล้วตั้งค่าใหม่ด้วย ` +
      `"firebase functions:secrets:set GITHUB_TOKEN" (ดู PHASE2_IMPLEMENTATION_NOTES.md หัวข้อการตั้งค่า)`
    );
  }
  if (status === 403) {
    return (
      `GITHUB_TOKEN ไม่มีสิทธิ์เพียงพอสำหรับ ${path} (GitHub ตอบ 403: ${ghMessage}) — ` +
      `ตรวจสอบว่า Token ตั้ง Resource owner เป็น TEF-All, เลือก repo tef-results-2567- และให้สิทธิ์ ` +
      `Contents: Read and write`
    );
  }
  if (status === 404) {
    return `ไม่พบไฟล์หรือ repo สำหรับ ${path} บน GitHub (404: ${ghMessage}) — ตรวจสอบชื่อ repo/branch ใน schema.js`;
  }
  if (status === 409 || status === 422) {
    return `GitHub ปฏิเสธการเขียนไฟล์ ${path} (${status}: ${ghMessage}) — อาจมีคนอื่นแก้ไฟล์เดียวกันพร้อมกัน ลองใหม่อีกครั้ง`;
  }
  return `GitHub API ล้มเหลวที่ ${path} (${status}: ${ghMessage})`;
}

async function getFile(token, path) {
  const res = await fetch(`${API_BASE}/${encodeURIComponent(path)}?ref=${GITHUB_BRANCH}`, {
    headers: authHeaders(token),
  });
  if (res.status === 404) return null;
  if (!res.ok) {
    const bodyText = await res.text();
    throw new Error(githubErrorMessage(res.status, path, bodyText));
  }
  const json = await res.json();
  return {
    sha: json.sha,
    content: Buffer.from(json.content, 'base64').toString('utf8'),
  };
}

async function putFile(token, path, content, message, sha) {
  const body = {
    message,
    content: Buffer.from(content, 'utf8').toString('base64'),
    branch: GITHUB_BRANCH,
  };
  if (sha) body.sha = sha;

  const res = await fetch(`${API_BASE}/${encodeURIComponent(path)}`, {
    method: 'PUT',
    headers: { ...authHeaders(token), 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const bodyText = await res.text();
    throw new Error(githubErrorMessage(res.status, path, bodyText));
  }
  const json = await res.json();
  return json.commit?.sha;
}

function buildPerYearJson(year, summary, events) {
  return JSON.stringify({ summary: { ...summary, year_be: Number(year) }, events }, null, 2);
}

function buildPerYearJs(year, jsonString) {
  return (
    `// Auto-generated by publishYear Cloud Function — do not hand-edit.\n` +
    `// Source of truth for this file lives in Firestore drafts, reviewed by an admin\n` +
    `// before every publish. See FUTURE_YEAR_DATA_SCHEMA.md for the entry schema.\n` +
    `window.TEF_DATA_BY_YEAR = window.TEF_DATA_BY_YEAR || {};\n` +
    `window.TEF_DATA_BY_YEAR['${year}'] = ${jsonString};\n`
  );
}

// Flips `status: "coming_soon"` -> `status: "available"` for the given year
// inside the TEF_YEARS_CONFIG block. Idempotent: if it's already "available",
// the string is left unchanged (no duplicate replace, no error).
function flipYearStatus(htmlSource, year) {
  const re = new RegExp(
    `(\\{\\s*year:\\s*["']${year}["'][\\s\\S]{0,120}?status:\\s*["'])coming_soon(["'])`
  );
  return htmlSource.replace(re, `$1available$2`);
}

// Inserts <script src="tef_master_data_<year>.js"></script> right after the
// tef_master_data.js tag, but only if a tag for this year isn't already
// present (so re-publishing the same year twice never duplicates the tag).
function ensureDataScriptTag(htmlSource, year) {
  const tagMarker = `tef_master_data_${year}.js`;
  if (htmlSource.includes(tagMarker)) return htmlSource;

  const anchor = '<script src="tef_master_data.js"></script>';
  const newTag = `<script src="tef_master_data_${year}.js"></script>`;
  if (!htmlSource.includes(anchor)) {
    // Shouldn't happen on the real repo, but fail loudly instead of silently
    // producing a page that doesn't load the new year's data at all.
    throw new Error(
      `Could not find anchor tag "${anchor}" to insert ${newTag} after — refusing to guess a location.`
    );
  }
  return htmlSource.replace(anchor, `${anchor}\n    ${newTag}`);
}

/**
 * @param {string} token GitHub token from the GITHUB_TOKEN secret
 * @param {string} year e.g. "2568"
 * @param {object} summary { total_items, total_entries }
 * @param {Array} events events array in the schema's per-year format
 * @param {string} commitMessageSuffix free text, e.g. the draft id / event name
 * @returns {Promise<{commits: Record<string,string>}>}
 */
async function publishYearToGithub(token, { year, summary, events, commitMessageSuffix }) {
  const jsonPath = `tef_master_data_${year}.json`;
  const jsPath = `tef_master_data_${year}.js`;
  const jsonString = buildPerYearJson(year, summary, events);
  const jsString = buildPerYearJs(year, jsonString);

  const commits = {};

  const existingJson = await getFile(token, jsonPath);
  commits[jsonPath] = await putFile(
    token,
    jsonPath,
    jsonString,
    `Publish ${year} results data (${commitMessageSuffix})`,
    existingJson?.sha
  );

  const existingJs = await getFile(token, jsPath);
  commits[jsPath] = await putFile(
    token,
    jsPath,
    jsString,
    `Publish ${year} results data JS wrapper (${commitMessageSuffix})`,
    existingJs?.sha
  );

  for (const htmlPath of ['index.html', 'tef_results_webapp.html']) {
    const existing = await getFile(token, htmlPath);
    if (!existing) {
      throw new Error(`Expected ${htmlPath} to already exist in the repo — refusing to create it fresh.`);
    }
    let updated = ensureDataScriptTag(existing.content, year);
    updated = flipYearStatus(updated, year);
    if (updated === existing.content) {
      // Nothing changed (year was already available + tag already present) —
      // skip the commit entirely rather than writing a no-op commit.
      continue;
    }
    commits[htmlPath] = await putFile(
      token,
      htmlPath,
      updated,
      `Mark ${year} as available in TEF_YEARS_CONFIG (${commitMessageSuffix})`,
      existing.sha
    );
  }

  return { commits };
}

module.exports = { publishYearToGithub, getFile, putFile, flipYearStatus, ensureDataScriptTag };
